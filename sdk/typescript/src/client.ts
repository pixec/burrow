/**
 * Runs `use` against a client opened for one call. Every handle `use` hands
 * back holds its own share of the connection, so closing the client here
 * leaves them working.
 */
export async function withClient<T>(
  options: TransportOptions,
  use: (burrow: Burrow) => Promise<T>,
): Promise<T> {
  const burrow = new Burrow(options);
  try {
    return await use(burrow);
  } finally {
    burrow.close();
  }
}

/** {@link withClient} for a call whose `timeoutMs` is its own deadline. */
export function withConnection<T>(
  options: ConnectionOptions,
  use: (burrow: Burrow) => Promise<T>,
): Promise<T> {
  return withClient({ ...options, timeoutMs: options.callTimeoutMs }, use);
}

/**
 * How many times {@link Sandboxes.getOrCreate} looks before giving up. Only a
 * lost race gets this far, waiting on another caller's create to finish.
 */
const GET_OR_CREATE_ATTEMPTS = 10;

const delay = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Sandboxes, through one client's connection. */
export class Sandboxes {
  /** @internal */
  constructor(private readonly transport: Transport) {}

  /** Creates a sandbox and waits for it to be ready to accept commands. */
  async create(options: CreateOptions = {}): Promise<Sandbox> {
    const raw = await this.transport.unary<any, any>(
      "CreateSandbox",
      Sandbox.createRequest(options),
      options.timeoutMs ?? 120_000,
      options.signal,
    );
    return new Sandbox(this.transport.retain(), toSandboxInfo(raw), options);
  }

  /**
   * Returns a handle for a sandbox that already exists.
   *
   * ```ts
   * const sandbox = await burrow.sandboxes.get("build-482");
   * ```
   */
  async get(options: GetOptions | string): Promise<Sandbox> {
    const params: GetOptions = typeof options === "string" ? { id: options } : options;
    // Ids and names share one lookup: the server resolves a reference as an
    // id first and as a name second, and the two cannot collide.
    if (!params.id) {
      throw new BurrowError("an id or a name is required", "invalid_argument");
    }
    const raw = await this.transport.unary<any, any>(
      "GetSandbox",
      { sandboxId: params.id },
      params.timeoutMs,
      params.signal,
    );
    return new Sandbox(this.transport.retain(), toSandboxInfo(raw), params);
  }

  /**
   * Returns the sandbox with this name, creating it if it is not there.
   *
   * ```ts
   * const sandbox = await burrow.sandboxes.getOrCreate({
   *   name: "build-482",
   *   template: "python-tools",
   *   onCreate: (s) => s.fs.writeFile("/work/app.py", src),
   * });
   * ```
   *
   * A `name` is the only key: ids are generated by the server, so there is no
   * id to ask for before the sandbox exists. The create options apply only
   * when it turns out not to exist, so the same call is safe from every
   * worker; an existing sandbox is handed back as it is. A suspended one stays
   * suspended unless `resume` is set, though the first call that needs a
   * running VM resumes it anyway.
   */
  async getOrCreate(options: GetOrCreateOptions = {}): Promise<Sandbox> {
    const key = options.name;
    if (!key) {
      throw new BurrowError(
        "getOrCreate needs a name: without one there is nothing to get",
        "invalid_argument",
      );
    }
    const { env, autoResume, onResume, signal, timeoutMs } = options;

    // Two processes racing on the same name both find nothing and both create.
    // The loser is told ALREADY_EXISTS while the winner's sandbox is still
    // booting, so the get is retried rather than made once.
    for (let attempt = 0; attempt < GET_OR_CREATE_ATTEMPTS; attempt++) {
      try {
        const sandbox = await this.get({ id: key, env, autoResume, onResume, signal, timeoutMs });
        if (options.resume && (sandbox.state === "paused" || sandbox.state === "suspended")) {
          await sandbox.resume();
        }
        return sandbox;
      } catch (err) {
        if (!(err instanceof BurrowError) || err.code !== "not_found") throw err;
      }

      try {
        const sandbox = await this.create(options);
        await options.onCreate?.(sandbox);
        return sandbox;
      } catch (err) {
        const lost = err instanceof BurrowError && err.code === "already_exists";
        if (!lost) throw err;
        // The winner's record appears once the node has built the sandbox.
        await delay(Math.min(200 * 2 ** attempt, 1_000));
      }
    }
    throw new BurrowError(
      `sandbox ${key} is being created elsewhere and did not become available`,
      "unavailable",
    );
  }

  /**
   * Lists sandboxes, newest state first, as an async iterable of handles.
   *
   * ```ts
   * for await (const sandbox of burrow.sandboxes.list({ tag: "owner=ci" })) {
   *   await sandbox.pause();
   * }
   * ```
   */
  list(options: ListOptions = {}): AsyncIterable<Sandbox> & { toArray(): Promise<Sandbox[]> } {
    const transport = this.transport;
    const iterate = async function* (): AsyncGenerator<Sandbox> {
      const res = await transport.unary<any, any>(
        "ListSandboxes",
        { tag: options.tag ?? "" },
        options.timeoutMs,
        options.signal,
      );
      for (const raw of res.sandboxes ?? []) {
        yield new Sandbox(transport.retain(), toSandboxInfo(raw), options);
      }
    };
    return {
      [Symbol.asyncIterator]: iterate,
      async toArray() {
        const all: Sandbox[] = [];
        for await (const sandbox of iterate()) all.push(sandbox);
        return all;
      },
    };
  }
}

/** Snapshots, through one client's connection. */
export class Snapshots {
  /** @internal */
  constructor(private readonly transport: Transport) {}

  /** Returns a handle for a snapshot that already exists. */
  async get(id: string, options: CallOptions = {}): Promise<Snapshot> {
    const raw = await this.transport.unary<any, any>(
      "GetSnapshot",
      { id },
      options.timeoutMs,
      options.signal,
    );
    return new Snapshot(this.transport.retain(), raw);
  }

  /** Lists snapshots, newest first. */
  async list(options: ListSnapshotsOptions = {}): Promise<Snapshot[]> {
    const res = await this.transport.unary<any, any>(
      "ListSnapshots",
      { sandboxId: options.sandboxId ?? "" },
      options.timeoutMs,
      options.signal,
    );
    return (res.snapshots ?? []).map((raw: any) => new Snapshot(this.transport.retain(), raw));
  }
}

/** Volumes, through one client's connection. */
export class Volumes {
  /** @internal */
  constructor(private readonly transport: Transport) {}

  /** Creates a volume, placing it on a node that satisfies `nodeLabels`. */
  async create(name: string, options: CreateVolumeOptions = {}): Promise<Volume> {
    const raw = await this.transport.unary<any, any>(
      "CreateVolume",
      {
        name,
        sizeMib: options.sizeMib ?? 1024,
        nodeLabels: options.nodeLabels ?? {},
        labels: options.labels ?? {},
      },
      options.timeoutMs,
      options.signal,
    );
    return new Volume(this.transport.retain(), raw);
  }

  /** Returns a handle for a volume that already exists. */
  async get(name: string, options: CallOptions = {}): Promise<Volume> {
    const raw = await this.transport.unary<any, any>(
      "GetVolume",
      { name },
      options.timeoutMs,
      options.signal,
    );
    return new Volume(this.transport.retain(), raw);
  }

  /** Lists volumes by name. */
  async list(options: ListVolumesOptions = {}): Promise<Volume[]> {
    const res = await this.transport.unary<any, any>(
      "ListVolumes",
      { nodeId: options.nodeId ?? "" },
      options.timeoutMs,
      options.signal,
    );
    return (res.volumes ?? []).map((raw: any) => new Volume(this.transport.retain(), raw));
  }
}

/** Templates, through one client's connection. */
export class Templates {
  /** @internal */
  constructor(private readonly transport: Transport) {}

  /** Builds a template and publishes it under `name`. */
  async build(
    template: TemplateBuilder,
    name: string,
    options: BuildOptions = {},
  ): Promise<BuildResult> {
    let result: BuildResult | undefined;
    for await (const raw of this.transport.serverStream<any, any>(
      "BuildTemplate",
      template.toRequest(name, options),
      // Builds install packages; minutes, not seconds.
      options.timeoutMs ?? 30 * 60_000,
      options.signal,
    )) {
      const event = toBuildEvent(raw);
      if (!event) continue;
      options.onBuildLogs?.(event);
      if (event.type === "done") {
        result = { template: event.template, sizeBytes: event.sizeBytes };
      }
    }
    if (!result) {
      throw new BurrowError("build ended without producing an image", "internal");
    }
    return result;
  }

  /** Lists the templates available across the fleet. */
  async list(options: CallOptions = {}): Promise<TemplateInfo[]> {
    const res = await this.transport.unary<any, any>(
      "ListTemplates",
      {},
      options.timeoutMs,
      options.signal,
    );
    return (res.templates ?? []).map(toTemplateInfo);
  }

  /** Deletes a template. */
  async delete(name: string, options: CallOptions = {}): Promise<void> {
    await this.transport.unary("DeleteTemplate", { name }, options.timeoutMs, options.signal);
  }
}

const EVENT_KINDS: readonly EventKind[] = [
  "created",
  "started",
  "agent_ready",
  "stopped",
  "destroyed",
  "snapshot_created",
  "recovered",
  "ip_attached",
  "ip_detached",
];

const USAGE_STATES: readonly UsageState[] = ["running", "suspended", "stopped"];

function usageStateOf(raw: unknown): UsageState {
  return enumOf(raw, "USAGE_STATE_", USAGE_STATES);
}

/**
 * A connection to a burrow control plane.
 *
 * ```ts
 * const burrow = new Burrow({ endpoint: "https://burrow.example.com" });
 * const sandbox = await burrow.sandboxes.create({ template: "python" });
 * ```
 *
 * Every handle made through it shares its channel. The static
 * {@link Sandbox.create} and its siblings open a client of their own for the
 * one call, which is the shortcut when there is only one sandbox.
 */
export class Burrow {
  /** @internal */
  transport: Transport;
  readonly sandboxes: Sandboxes;
  readonly snapshots: Snapshots;
  readonly volumes: Volumes;
  readonly templates: Templates;
  /** Dedicated public IPs and their pools. */
  readonly ips: Ips;

  constructor(options: TransportOptions = {}) {
    this.transport = new Transport(options);
    this.sandboxes = new Sandboxes(this.transport);
    this.snapshots = new Snapshots(this.transport);
    this.volumes = new Volumes(this.transport);
    this.templates = new Templates(this.transport);
    this.ips = new Ips(this.transport);
  }

  async health(options: CallOptions = {}): Promise<{ version: string }> {
    const res = await this.transport.unary<any, any>(
      "Health",
      {},
      options.timeoutMs,
      options.signal,
    );
    return { version: res.version ?? "" };
  }

  /**
   * Reads the egress audit trail, newest first.
   *
   * Records cover both connection attempts and DNS lookups, so an attempt is
   * visible even when the policy blocked it.
   */
  async *audit(query: AuditQuery = {}): AsyncGenerator<AuditEvent> {
    for await (const raw of this.transport.serverStream<any, any>(
      "QueryAudit",
      {
        sandboxId: query.sandboxId ?? "",
        isDeniedOnly: query.deniedOnly ?? false,
        sinceUnixMs: msOf(query.since),
        limit: query.limit ?? 0,
      },
      query.timeoutMs,
      query.signal,
    )) {
      yield {
        at: dateOf(raw.atUnixMs),
        sandboxId: raw.sandboxId,
        sourceIp: raw.sourceIp,
        destination: raw.destination,
        host: raw.host ?? "",
        port: Number(raw.port ?? 0),
        allowed: Boolean(raw.isAllowed),
        reason: raw.reason ?? "",
        bytesSent: Number(raw.bytesSent ?? 0),
        bytesReceived: Number(raw.bytesReceived ?? 0),
        nodeId: raw.nodeId ?? "",
      };
    }
  }

  /**
   * Reads the fleet's lifecycle log, oldest first.
   *
   * Without `follow` the iterator ends after the replay. With it, the stream
   * stays open and yields events as they happen until `signal` aborts or the
   * loop breaks. Keep the last `seq` seen to resume after a disconnect.
   *
   * ```ts
   * for await (const event of burrow.events({ sandboxId: "build-482", follow: true })) {
   *   console.log(event.seq, event.kind, event.detail);
   * }
   * ```
   */
  async *events(options: EventsOptions = {}): AsyncGenerator<LifecycleEvent> {
    for await (const raw of this.transport.serverStream<any, any>(
      "TailEvents",
      {
        afterSeq: options.after ?? 0,
        sandboxId: options.sandboxId ?? "",
        isFollow: options.follow ?? false,
        limit: options.limit ?? 0,
      },
      // A follow outlives any request deadline.
      options.follow ? Infinity : options.timeoutMs,
      options.signal,
    )) {
      yield {
        seq: Number(raw.seq ?? 0),
        nodeId: raw.nodeId ?? "",
        nodeSeq: Number(raw.nodeSeq ?? 0),
        at: dateOf(raw.atUnixMs),
        sandboxId: raw.sandboxId ?? "",
        kind: enumOf(raw.kind, "EVENT_KIND_", EVENT_KINDS),
        state: Sandbox.stateOf(raw.state),
        detail: raw.detail ?? "",
        template: raw.template ?? "",
        tags: raw.tags ?? {},
        cpuUsageUsec: Number(raw.cpuUsageUsec ?? 0),
        rxBytes: Number(raw.rxBytes ?? 0),
        txBytes: Number(raw.txBytes ?? 0),
        vcpus: Number(raw.vcpus ?? 0),
        memoryMib: Number(raw.memMib ?? 0),
      };
    }
  }

  /**
   * Reads the usage ledger: the intervals sandboxes spent in one state at one
   * shape, or their sums by group. The ledger outlives the sandboxes and
   * nodes it describes.
   *
   * ```ts
   * const { sums } = await burrow.usage({
   *   from: new Date("2026-10-01"),
   *   to: new Date("2026-11-01"),
   *   groupBy: "tag:customer",
   * });
   * ```
   */
  async usage(query: UsageQuery = {}): Promise<UsageReport> {
    const tag = query.groupBy?.startsWith("tag:") ? query.groupBy.slice(4) : "";
    const group = query.groupBy === undefined ? "UNSPECIFIED" : tag ? "TAG" : query.groupBy.toUpperCase();
    const res = await this.transport.unary<any, any>(
      "QueryUsage",
      {
        fromUnixMs: msOf(query.from),
        toUnixMs: msOf(query.to),
        sandboxId: query.sandboxId ?? "",
        tags: query.tags ?? {},
        groupBy: `USAGE_GROUP_${group}`,
        groupByTag: tag,
        afterId: query.afterId ?? 0,
        limit: query.limit ?? 0,
        isOpenIncluded: query.includeOpen ?? true,
      },
      query.timeoutMs,
      query.signal,
    );
    return {
      intervals: (res.intervals ?? []).map(
        (raw: any): UsageInterval => ({
          id: Number(raw.id ?? 0),
          sandboxId: raw.sandboxId ?? "",
          nodeId: raw.nodeId ?? "",
          template: raw.template ?? "",
          tags: raw.tags ?? {},
          state: usageStateOf(raw.state),
          vcpus: Number(raw.vcpus ?? 0),
          memoryMib: Number(raw.memMib ?? 0),
          startedAt: dateOf(raw.startedAtUnixMs),
          endedAt: dateOrNull(raw.endedAtUnixMs),
          cpuUsageUsec: Number(raw.cpuUsageUsec ?? 0),
          rxBytes: Number(raw.rxBytes ?? 0),
          txBytes: Number(raw.txBytes ?? 0),
          closedBy: raw.closedBy ?? "",
          open: Boolean(raw.isOpen),
        }),
      ),
      sums: (res.sums ?? []).map(
        (raw: any): UsageSum => ({
          group: raw.group ?? "",
          state: usageStateOf(raw.state),
          intervals: Number(raw.intervals ?? 0),
          durationMs: Number(raw.durationMs ?? 0),
          vcpuMs: Number(raw.vcpuMs ?? 0),
          memoryMibMs: Number(raw.memMibMs ?? 0),
          cpuUsageUsec: Number(raw.cpuUsageUsec ?? 0),
          rxBytes: Number(raw.rxBytes ?? 0),
          txBytes: Number(raw.txBytes ?? 0),
        }),
      ),
      nextAfterId: Number(res.nextAfterId ?? 0),
    };
  }

  /**
   * Stops placing new sandboxes on a node. {@link undrainNode} lifts it.
   * Refused while sandboxes on it hold public IPs, unless `keepPinned`.
   */
  async drainNode(
    nodeId: string,
    options: DrainOptions = {},
  ): Promise<{ suspended: number; pinnedSandboxIds: string[] }> {
    const res = await this.transport.unary<any, any>(
      "DrainNode",
      {
        nodeId,
        isDraining: true,
        isSuspending: options.suspend ?? false,
        isPinnedKept: options.keepPinned ?? false,
      },
      options.timeoutMs,
      options.signal,
    );
    return {
      suspended: Number(res.suspended ?? 0),
      pinnedSandboxIds: res.pinnedSandboxIds ?? [],
    };
  }

  /** Lets a drained node take sandboxes again. */
  async undrainNode(nodeId: string, options: CallOptions = {}): Promise<void> {
    await this.transport.unary(
      "DrainNode",
      { nodeId, isDraining: false, isSuspending: false },
      options.timeoutMs,
      options.signal,
    );
  }

  /**
   * Stores a credential that Sandbox Kits ask for by service name. The value
   * stays on the node and is injected into matching requests by the egress
   * proxy, so a guest never holds it. `name` is lowercase kebab-case, the
   * `service` a Kit credential names.
   *
   * `scope` limits which sandboxes may use it, by id or name or by tag; a
   * reference from any other sandbox is refused. Omitted, every sandbox may.
   * Setting a secret replaces its scope along with its value.
   */
  async setSecret(
    name: string,
    value: string,
    scope: SecretScope & CallOptions = {},
  ): Promise<void> {
    await this.transport.unary(
      "SetSecret",
      {
        name,
        value,
        allowedSandboxes: scope.sandboxes ?? [],
        allowedTags: scope.tags ?? [],
      },
      scope.timeoutMs,
      scope.signal,
    );
  }

  /** The stored secrets with their scopes. Values are never returned. */
  async listSecrets(options: CallOptions = {}): Promise<SecretInfo[]> {
    const res = await this.transport.unary<any, any>(
      "ListSecrets",
      {},
      options.timeoutMs,
      options.signal,
    );
    return (res.secrets ?? []).map((secret: any) => ({
      name: secret.name ?? "",
      scope: {
        sandboxes: [...(secret.allowedSandboxes ?? [])],
        tags: [...(secret.allowedTags ?? [])],
      },
    }));
  }

  async deleteSecret(name: string, options: CallOptions = {}): Promise<void> {
    await this.transport.unary("DeleteSecret", { name }, options.timeoutMs, options.signal);
  }

  async nodes(options: CallOptions = {}): Promise<NodeInfo[]> {
    const res = await this.transport.unary<any, any>(
      "ListNodes",
      {},
      options.timeoutMs,
      options.signal,
    );
    return (res.nodes ?? []).map((n: any): NodeInfo => {
      const disk = n.status?.disk;
      return {
        id: n.info?.id ?? "",
        address: n.info?.address ?? "",
        hostname: n.info?.hostname ?? "",
        totalVcpus: Number(n.info?.totalVcpus ?? 0),
        totalMemoryMib: Number(n.info?.totalMemMib ?? 0),
        freeMemoryMib: Number(n.status?.freeMemMib ?? 0),
        runningSandboxes: Number(n.status?.runningSandboxes ?? 0),
        healthy: Boolean(n.isHealthy),
        draining: Boolean(n.status?.isDraining),
        lastHeartbeatAt: dateOf(n.lastHeartbeatAtUnixMs),
        labels: n.info?.labels ?? {},
        arch: n.info?.arch ?? "",
        hypervisorVersions: n.info?.hypervisorVersions ?? {},
        disk: disk
          ? {
              freeBytes: Number(disk.freeBytes ?? 0),
              totalBytes: Number(disk.totalBytes ?? 0),
              reserveBytes: Number(disk.reserveBytes ?? 0),
              unwrittenBytes: Number(disk.unwrittenBytes ?? 0),
              overcommit: Number(disk.overcommit ?? 0),
            }
          : undefined,
        diskLow: Boolean(n.status?.isDiskLow),
      };
    });
  }

  close(): void {
    this.transport.close();
  }

  [Symbol.dispose](): void {
    this.close();
  }
}
